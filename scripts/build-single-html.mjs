import { fileURLToPath } from 'node:url';
import { INLINE_AUDIO } from './audio-assets.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEV_MODE = process.argv.includes('--dev');
// === 瘦身开关 (体积逼近平台上传阈值时的两个杠杆) ===
//   --no-4k-sky  不再内联 11.35MB 的 4K 天空盒(仍随行放在 dist-single/assets/),
//                单文件改用已内联的 2K 版 —— 省约 15MB base64。
//   --slim       等价于 --no-4k-sky(留给以后加更多开关)。
const NO_4K_SKY = process.argv.includes('--no-4k-sky') || process.argv.includes('--slim');

