// === KTX2 compressed texture sets (per user request: 贴图/显存压缩) ===
// Generated by scripts/ktx2-export.mjs (procedural demo sets + textures-src
// overrides). The manifest lists which set ids exist; each set is 6 KTX2
// files. In single-file builds the transcoder (/basis/*) is inlined too.
const KTX2_CHANNELS = ['albedo', 'normal', 'metallic', 'roughness', 'ao', 'emissive'];
let KTX2_SETS = [];
try {
  const ktx2Manifest = JSON.parse(readFileSync(join(ROOT, 'public', 'textures', 'ktx2', 'manifest.json'), 'utf8'));
  KTX2_SETS = Array.isArray(ktx2Manifest.sets) ? ktx2Manifest.sets : [];
} catch {
  KTX2_SETS = [];
}
const KTX2_ASSETS = [
  // Basis Universal transcoder — fetched by three's KTX2Loader via
  // setTranscoderPath('/basis/'), remapped to the manifest at runtime.
  '/basis/basis_transcoder.js',
  '/basis/basis_transcoder.wasm',
];
for (const id of KTX2_SETS) {
  for (const ch of KTX2_CHANNELS) {
    KTX2_ASSETS.push(`/textures/ktx2/${id}/${ch}.ktx2`);
  }
}

// === 地形图层 KTX2 (per user request: MWAM 地形贴图) ===
// 由 scripts/mwam-import.mjs 生成:manifest.terrains = { 'terrain/<layer>':
// ['albedo','normal', …] } — 只列实际产出的通道(地形层不是六通道套件,
// 不能套 KTX2_CHANNELS 交叉,否则为不存在的通道刷一堆 missing 告警)。
const KTX2_TERRAIN_ASSETS = [];
try {
  const tManifest = JSON.parse(readFileSync(join(ROOT, 'public', 'textures', 'ktx2', 'manifest.json'), 'utf8'));
  const terrains = tManifest.terrains ?? {};
  for (const [id, channels] of Object.entries(terrains)) {
    for (const ch of Array.isArray(channels) ? channels : []) {
      KTX2_TERRAIN_ASSETS.push(`/textures/ktx2/${id}/${ch}.ktx2`);
    }
  }
} catch {
  // 没有地形图层时跳过(纯程序化画布模式仍可用)
}

// === MiG-29 贴图 (per user request: 加入可玩机体) ===
