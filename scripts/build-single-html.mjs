#!/usr/bin/env node
// scripts/build-single-html.mjs
//
// Builds a single self-contained HTML file of the ACE/SKY game:
//   dist-single/ACE-SKY.html
//
// The file inlines EVERYTHING: the JS bundle (React 19 + three + game code),
// the compiled Tailwind CSS, and all real game assets (F-16/B-52 OBJ models
// + the 17 audio files actually referenced by the game code) as base64 data
// URIs in a window.__ASSET_MANIFEST map. Double-click it and it plays fully
// offline — no server, no sibling files, no network.
//
// Redundant files in public/ (fa18a.obj 41MB, quitv3.obj 49MB, unused music,
// draco/gltf duplicates, …) are deliberately NOT included.
//
// Usage: node scripts/build-single-html.mjs [--dev]
// Requires (devDependencies): esbuild, @tailwindcss/postcss, postcss.
//
// --dev: no base64 inlining (manifest stays empty → assetUrl() falls back to
// the real /models /audio URLs). Outputs dist-test/index.html — serve it
// together with the repo's public/ directory for a fast test loop.

import { build } from 'esbuild';
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, copyFileSync, statSync, rmSync } from 'node:fs';
