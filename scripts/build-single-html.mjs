//   dist-single/assets/               ← 游戏随行资产库(4K 天空盒)
//   dist-editor/index.html            ← 地形编辑器产物
//   dist-editor/fx-editor.html        ← FX 编辑器产物
//   dist-test/index.html              ← dev 游戏(serve-test)
//   dist-editor-test/…                ← dev 编辑器
// 编辑器里的资产库根用 `../dist-single/assets`(兄弟目录), 这样不必把 11MB 的
// 天空盒再拷一份; 取不到时引擎自动回退到已内联的 2K 天空。
