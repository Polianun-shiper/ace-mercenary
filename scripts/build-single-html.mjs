// 资产库相对 URL 解析", 这边决定"构建时哪些文件拷进 <out>/assets/"。一份名单
// 两处消费, 从结构上消灭"URL 指向资产库但库里没这个文件"的 404 漂移。
const ASSET_LIBRARY = JSON.parse(readFileSync(join(ROOT, 'src', 'lib', 'game', 'asset-library.json'), 'utf8'));
/** 资产库根目录名(与 entry.tsx 的 __EXTERNAL_ASSETS.root 必须一致)。 */
const ASSET_LIB = ASSET_LIBRARY.assetRoot || 'assets';
// --inline-library: 库内资产也全部内联 → 单文件重新变成自包含(离线双击保险开关)。
// 平台若不提供"同目录静态文件", 上传前用它重新构建即可。
const INLINE_LIBRARY = process.argv.includes('--inline-library');

/**
 * 展开资产库前缀 → public/ 下的实际文件清单。
 * copyOnly=true 只收 copy:true 的条目(= 要拷进资产库的), false 收全部。
 */
function collectLibraryFiles(copyOnly = true) {
  const out = [];
  const walk = (absDir, urlDir) => {
    for (const f of readdirSync(absDir, { withFileTypes: true })) {
      const abs = join(absDir, f.name);
      const url = `${urlDir}/${f.name}`;
      if (f.isDirectory()) walk(abs, url);
      else out.push(url);
    }
  };
  for (const e of ASSET_LIBRARY.entries) {
    if (copyOnly && !e.copy) continue;
    const abs = join(ROOT, 'public', e.prefix.replace(/^\//, ''));
    if (!existsSync(abs)) {
      console.warn(`  [warn] asset-library: ${e.prefix} 在 public/ 下不存在, 跳过`);
      continue;
    }
    if (statSync(abs).isDirectory()) walk(abs, e.prefix.replace(/\/$/, ''));
    else out.push(e.prefix);
  }
  return out;
}

const EXTERNAL_FILES = collectLibraryFiles(true);
// --inline-library: 把库内资产补进内联清单(必须在下面的内联循环之前完成)。
if (INLINE_LIBRARY) {
  for (const p of collectLibraryFiles(false)) if (!ASSETS.includes(p)) ASSETS.push(p);
}
/**
 * 前缀匹配 —— 与 src/lib/game/asset-url.ts 的 matchesPrefix() 语义**必须一致**
 * (目录条目以 '/' 结尾按目录匹配, 否则按路径本身或其后紧跟分隔符匹配)。
 */
function matchesPrefix(path, prefix) {
  if (prefix.endsWith('/')) return path.startsWith(prefix);
  return path === prefix || path.startsWith(prefix + '/') || path.startsWith(prefix + '.');
}
/** 该路径是否"只入资产库、不进单文件"(登记条目 inline:false)。 */
function isLibraryOnly(path) {
  return ASSET_LIBRARY.entries.some((e) => !e.inline && matchesPrefix(path, e.prefix));
}
// 一致性自检: 标了 inline:true 的条目在 ASSETS 里必须真有文件, 否则就是
// "说好离线可玩、实际没内联"的静默失效(以前只能靠人肉比对两张清单)。
for (const e of ASSET_LIBRARY.entries) {
  if (!e.inline) continue;
  const hit = ASSETS.some((p) => matchesPrefix(p, e.prefix));
  if (!hit) console.warn(`  [warn] asset-library: ${e.prefix} 标了 inline:true, 但 ASSETS 清单里没有对应文件`);
}

const MIME = {
  '.obj': 'application/octet-stream',
  '.bin': 'application/octet-stream',
  '.f32bin': 'application/octet-stream',
  // gzip 内联包(f16c.obj.gz / MiG-29.obj.gz / heights.f32bin.gz)——运行时由
  // pako.inflate 解压,绝不能让浏览器按 Content-Encoding 自动解一遍。
  '.gz': 'application/octet-stream',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav',
  '.ktx2': 'application/octet-stream',
  '.mtl': 'application/octet-stream',
  '.json': 'application/json',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.exr': 'image/x-exr',
};

// System font stack replacing Geist (next/font) in the single-file build.
const FONT_OVERRIDE_CSS = `:root {
  --font-geist-sans: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, "Noto Sans", "PingFang SC", "Microsoft YaHei", sans-serif;
  --font-geist-mono: ui-monospace, SFMono-Regular, Menlo, Consolas, "Liberation Mono", "Courier New", monospace;
}
html, body { background: #000; }
`;

function readAsset(publicPath) {
  const file = join(ROOT, 'public', publicPath.replace(/^\//, ''));
  if (!existsSync(file)) {
    console.warn(`[warn] missing asset, skipping: ${publicPath}`);
    return null;
  }
  // === 大文件门限 (per user request: 高分辨率 custom 高度包) ===
  // f32bin 高度包 2048²=16MiB 内联尚可;4096²=64MiB/8192²=256MiB 内联会
  // base64 膨胀 +33% 且单 HTML 超部署上限 → 跳过并警告(由 dist-single
  // 外置/或 dev http 提供;游戏内 __ASSET_MANIFEST 缺失时回退程序化山)。
  const stat = statSync(file);
  if (stat.size > 64 * 1024 * 1024) { // 门限 32→64MB:含 MiG-29(37MB)进单文件
    console.warn(`[warn] ${publicPath} 太大(${Math.round(stat.size / 1048576)}MiB),跳过内联 —— 单文件构建不含此资产`);
    return null;
  }
  const buf = readFileSync(file);
  const mime = MIME[extname(publicPath).toLowerCase()] ?? 'application/octet-stream';
  return { uri: `data:${mime};base64,${buf.toString('base64')}`, rawBytes: buf.length };
}

async function main() {
  // === [-1/4] Gzip the big text OBJ airframes (per user request: 单文件 ≤100MB) ===
  // f16c.obj / MiG-29.obj → <name>.obj.gz (level 9, 5.5× 压缩)。已是最新则跳过;
  // 重新导出 OBJ 后会自动重压。必须在下面读清单之前跑完。
  try {
    const { ensureGzippedObjs, ensureGzippedSkies } = await import('./gzip-obj-assets.mjs');
    for (const r of ensureGzippedObjs()) {
      console.log(`  [gzip-obj] ${r.skipped ? 'up-to-date' : 'wrote'} ${r.gz}: ` +
        `${(r.raw / 1048576).toFixed(2)} MiB → ${(r.gzBytes / 1048576).toFixed(2)} MiB (${r.ratio.toFixed(2)}×)`);
    }
    // 天空盒 EXR 的 gzip -9(无损, 只为省 base64;见 ASSETS 里 evening-046b 的注释)。
    for (const r of ensureGzippedSkies()) {
      console.log(`  [gzip-sky] ${r.skipped ? 'up-to-date' : 'wrote'} ${r.gz}: ` +
        `${(r.raw / 1048576).toFixed(2)} MiB → ${(r.gzBytes / 1048576).toFixed(2)} MiB (${r.ratio.toFixed(3)}×)`);
    }
  } catch (err) {
    console.warn('[-1/4] OBJ gzip skipped:', err?.message ?? err);
  }

  // === [0/4] Re-encode oversized audio (per user request: 优化加载速度) ===
  // 320kbps source files → 128kbps, shrinking the inlined audio ~60%.
  // No-op (idempotent) once files are already compressed; skips silently
  // when ffmpeg-static isn't installed.
  try {
    const { compressAudio } = await import('./compress-audio.mjs');
    await compressAudio();
  } catch (err) {
    console.warn('[0/4] audio compression skipped:', err?.message ?? err);
  }

  console.log('[1/4] Compiling Tailwind CSS …');
  const cssSrc = readFileSync(join(ROOT, 'src/app/globals.css'), 'utf8');
  const pc = await postcss([tailwindcss]).process(cssSrc, {
    from: join(ROOT, 'src/app/globals.css'),
  });
  const cssMinResult = await build({
    stdin: { contents: pc.css, loader: 'css', sourcefile: 'app.css' },
    write: false,
    minify: true,
  });
  const css = cssMinResult.outputFiles[0].text;

  console.log('[2/4] Inlining assets as base64 data URIs …');
  let rawBytes = 0;
  const manifest = {};
  if (DEV_MODE) {
    console.log('  (--dev: skipping inlining; assets served from public/)');
  } else {
    // === 政策硬约束 (per user request: 新导入资产压缩后放资产库) ===
    // 登记为 inline:false 的资产**即使出现在 ASSETS 清单里也不内联** —— 这条让
    // "政策"变成结构约束而不是约定: 以后新导入的机体/贴图/地形贴图只要按
    // import-asset.mjs 入库, 就绝不会偷偷把单文件 HTML 顶大。(--inline-library
    // 是显式的例外开关。)
    let libOnly = 0;
    for (const p of ASSETS) {
      if (!INLINE_LIBRARY && isLibraryOnly(p)) { libOnly++; continue; }
      const a = readAsset(p);
      if (!a) continue;
      manifest[p] = a.uri;
      rawBytes += a.rawBytes;
    }
    if (libOnly) console.log(`  资产库托管: ${libOnly} 个文件不内联(随 assets/ 发布)`);
  }
  const base64Bytes = Object.values(manifest).reduce((n, u) => n + u.length, 0);

  // === [2.5/4] 随行资产库 → <out>/assets/ (per user request) ===
  // 完全单文件结构不可持续:模型与贴图 base64 内联会把 HTML 顶到 96MB, 每次改动
  // 都要整包重传。改为"HTML 留引擎与 UI + 资产库随行":
  //   dist-single/index.html          ← 引擎 + UI
  //   dist-single/assets/models/...   ← 新导入的机体/贴图/地形贴图(本段拷出)
  // 运行时 entry.tsx 设 __EXTERNAL_ASSETS.root='assets'; assetUrl() 对命中
  // isExternalAsset() 的路径前缀 'assets'。
  //
  // 名单来自单一真相源 src/lib/game/asset-library.json(模块顶部已加载):
  // 拷哪些(copy)、内联哪些(inline)、运行时按库解析哪些(external) 与
  // asset-url.ts 读的是**同一个文件**, 结构上不再有"两边漂移 → 404"。
  // 政策: 以后导入的新机体/贴图/地形贴图 = 先压缩(import-asset.mjs) →
  // copy:true / inline:false, 即"压缩后放进资产库文件夹"。
  // === 随行资产库 → dist-test/(dev) 或 dist-single/(产物) ===
  // 分工(per user request):
  //   dist-test/   = 双击/本地测试用(--dev); 资产库也一起生成, 便于直接对外服务
  //   dist-single/ = **上传游玩**的成品; 模型与贴图全内联(见上面清单),
  //                  这里只额外拷不需要读像素的随行文件。
  const ASSET_OUT = join(ROOT, DEV_MODE ? 'dist-test' : 'dist-single');
  let extRawBytes = 0;
  {
    // === 先清理陈旧资产库 (per fix: 构建产物残留) ===
    // 之前不清目录, 于是"某一轮把模型/贴图放资产库、下一轮又改回内联"之后,
    // 旧文件会永久留在 dist-single/assets/ 里被一起传上去(白白多传 ~18MB)。
    // 只删产物侧的 assets 与旧随行 textures 目录; public/ 源文件不动。
    for (const stale of [join(ASSET_OUT, ASSET_LIB), join(ASSET_OUT, 'textures')]) {
      try { rmSync(stale, { recursive: true, force: true }); } catch { /* ignore */ }
    }
    for (const p of EXTERNAL_FILES) {
      const src = join(ROOT, 'public', p.replace(/^\//, ''));
      if (!existsSync(src)) { console.warn(`[warn] missing external asset, skipping: ${p}`); continue; }
      // 目标: <outDir>/assets/<原路径> —— assetUrl() 返回 'assets' + p, 所以必须
      // 保留完整层级, 不能压平。
      const dst = join(ASSET_OUT, ASSET_LIB, p.replace(/^\//, ''));
      mkdirSync(dirname(dst), { recursive: true });
      copyFileSync(src, dst);
      extRawBytes += readFileSync(src).length;
    }
    console.log(`  资产库       : ${EXTERNAL_FILES.length} 个文件 → ${DEV_MODE ? 'dist-test' : 'dist-single'}/${ASSET_LIB}/ (${(extRawBytes / 1048576).toFixed(1)} MB)`);
    if (INLINE_LIBRARY) console.log('  --inline-library: 库内资产同时内联进单文件(离线自包含)');
  }

  console.log('[3/4] Bundling game JS (esbuild) …');
  const jsResult = await build({
    entryPoints: ENTRIES.map((e) => join(ROOT, e.entry)),
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    jsx: 'automatic',
    alias: { '@': join(ROOT, 'src') },
    define: { 'process.env.NODE_ENV': '"production"' },
    legalComments: 'none',
    // === three KTX2Loader import.meta 修复 (per user request: 单文件 KTX2 无效) ===
    // esbuild 在 format:'iife' 下把 import.meta.url 替换成空对象属性(undefined),
    // KTX2Loader 模块初始化里的 new URL('../libs/basis/...wasm', import.meta.url)
    // 直接抛 TypeError → 单文件版所有 KTX2(飞机/地形)静默回退画布。这两条
    // URL 只在 transcoderPath==='' 分支使用;运行时永远 setTranscoderPath
    // ('/basis/'),故安全替换为空串,初始化不再抛错。
    plugins: [{
      name: 'ktx2-import-meta-fix',
      setup(b) {
        b.onLoad({ filter: /three[\\/]examples[\\/]jsm[\\/]loaders[\\/]KTX2Loader\.js$/ }, (args) => {
          let code = readFileSync(args.path, 'utf8');
          code = code.replace(
            /new URL\(\s*'\.\.\/libs\/basis\/basis_transcoder\.(wasm|js)'\s*,\s*import\.meta\.url\s*\)\.toString\(\s*\)/g,
            '""',
          );
          return { contents: code, loader: 'js' };
        });
      },
    }],
    write: false,
    // 多入口必须给 outdir(write:false 不落盘,只用于 outputFiles 命名)
    outdir: join(ROOT, '.esbuild-tmp'),
    metafile: true,
    logLevel: 'silent',
  });
  console.log('[4/4] Assembling single-file HTML …');
  const outDir = join(ROOT, DEV_MODE ? 'dist-test' : 'dist-single');
  mkdirSync(outDir, { recursive: true });
  const mb = (n) => (n / 1024 / 1024).toFixed(1) + ' MB';
  console.log('\n=== build complete' + (DEV_MODE ? ' (dev)' : '') + ' ===');
  console.log(`  CSS            : ${mb(Buffer.byteLength(css))}`);
  console.log(`  Assets inlined : ${Object.keys(manifest).length} files, ${mb(rawBytes)} raw → ${mb(base64Bytes)} base64`);

  for (let i = 0; i < ENTRIES.length; i++) {
    const e = ENTRIES[i];
    const js = jsResult.outputFiles[i]?.text;
    if (!js) {
      console.warn(`  [warn] missing bundle output for ${e.entry}, skipping`);
      continue;
    }
    const html = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${e.title}</title>
<meta name="description" content="${e.desc}">
<style>
${FONT_OVERRIDE_CSS}
${css}
</style>
<script>${DEV_MODE ? '' : `window.__ASSET_LIB = ${JSON.stringify(e.assetLib ?? ASSET_LIB)};`}window.__ASSET_MANIFEST = ${JSON.stringify(manifest)};
window.__KTX2_MANIFEST = ${JSON.stringify(KTX2_SETS)};</script>
<!-- === VibeHub SDK (P1-1) ===
     必须是**绝对地址**: 游戏页面在 vibeapps 域, 相对路径会 404(规范红线)。
     稳定通道 /sdk/v3/*: 普通作品必须用它, 不得自动迁到 beta。
     必须在游戏 JS 之前加载 —— 游戏代码通过 window.VibeHub 访问它。 -->
<script src="https://vibe.lumigrav.space/sdk/v3/vibehub.js"></script>
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;
    // 每个入口写到自己的输出根(游戏 vs 编辑器), 见 outDirFor()
    const outFile = join(outDirFor(e), e.out);
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, html, 'utf8');
    console.log(`  ${(e.scope === 'editor' ? 'editor/' : '') + e.out}`.padEnd(24) + ` JS ${mb(Buffer.byteLength(js))} → ${outFile} (${mb(Buffer.byteLength(html))})`);
  }
  if (DEV_MODE) {
    console.log('  Serve:  node scripts/serve-test.mjs   (http://127.0.0.1:8898)');
    console.log('  游戏:   /            编辑器: /editor/index.html   FX: /editor/fx-editor.html');
  } else {
    console.log('  部署:  上传 dist-single/index.html' +
      (EXTERNAL_FILES.length ? ` + dist-single/${ASSET_LIB}/ (${EXTERNAL_FILES.length} 个随行资产)` : ' —— 单文件自包含'));
    console.log(`  资产库: ${EXTERNAL_FILES.length} 个文件; 新导入资产用 node scripts/import-asset.mjs 压缩登记`);
    console.log('  编辑器: dist-editor/ 与 dist-single/ **平级**(不参与上传)');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
